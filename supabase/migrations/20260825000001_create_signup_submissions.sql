create table if not exists public.signup_submissions (
  id bigint generated by default as identity primary key,
  auth_user_id uuid references auth.users(id) on delete set null,
  first_name text not null,
  last_name text not null,
  email text not null,
  company_name text not null,
  phone_country text not null,
  phone_number text not null,
  job_role text,
  plan text not null default 'starter',
  created_at timestamptz not null default now()
);

alter table public.signup_submissions enable row level security;

revoke all on table public.signup_submissions from anon, authenticated;
grant insert on table public.signup_submissions to anon, authenticated;

drop policy if exists "Anyone can submit signup details" on public.signup_submissions;
create policy "Anyone can submit signup details"
  on public.signup_submissions
  for insert
  to anon, authenticated
  with check (
    length(trim(first_name)) between 1 and 120
    and length(trim(last_name)) between 1 and 120
    and length(trim(email)) between 3 and 320
    and position('@' in email) > 1
    and length(trim(company_name)) between 1 and 200
    and length(trim(phone_country)) between 2 and 8
    and length(trim(phone_number)) between 3 and 40
    and length(coalesce(job_role, '')) <= 120
    and plan in ('starter', 'team', 'business')
  );
